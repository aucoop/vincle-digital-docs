function detectarIdioma() {
  const pedido = new URLSearchParams(location.search).get('lang');
  if (pedido in IDIOMAS) {
    try { localStorage.setItem(CLAVE_IDIOMA, pedido); } catch { /* sin almacenamiento */ }
    return pedido;
  }
  try {
    const guardado = localStorage.getItem(CLAVE_IDIOMA);
    if (guardado in IDIOMAS) return guardado;
  } catch { /* sin almacenamiento */ }
  for (const l of navigator.languages ?? [navigator.language]) {
    const base = String(l).slice(0, 2).toLowerCase();
    if (base in IDIOMAS) return base;
  }
  return 'es';
}

const idioma = detectarIdioma();

// t('clave', {var}) con el texto del idioma actual; si falta, el castellano.
function t(clave, vars = {}) {
  const texto = TEXTOS[idioma][clave] ?? TEXTOS.es[clave] ?? clave;
  return texto.replace(/\{(\w+)\}/g, (_, v) => String(vars[v] ?? ''));
}

function cambiarIdioma(nuevo) {
  try { localStorage.setItem(CLAVE_IDIOMA, nuevo); } catch { /* sin almacenamiento */ }
  // Quita ?lang= para que no vuelva a imponerse al recargar.
  location.replace(location.pathname + location.hash);
}

// data-i18n: texto; data-i18n-html: HTML de confianza (solo de TEXTOS);
// data-i18n-attr="atributo:clave; …".
function traducirDocumento() {
  document.documentElement.lang = idioma;
  document.title = t('doc.titulo');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('doc.descripcion'));
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    el.dataset.i18nAttr.split(';').forEach((par) => {
      const [attr, clave] = par.split(':').map((s) => s.trim());
      if (attr && clave) el.setAttribute(attr, t(clave));
    });
  });
}
